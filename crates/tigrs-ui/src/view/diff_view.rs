    #[test]
    fn test_word_diff_rendered_text_is_unchanged_by_emphasis() {
        // Emphasis must only add escape sequences; the visible characters of
        // the row must be byte-identical with the feature on and off.
        let diff = diff_with_lines(vec![
            hunk_line(DiffLineKind::Remove, "let total = old_name(a);"),
            hunk_line(DiffLineKind::Add, "let total = new_name(a);"),
        ]);
        let view = DiffView::new(diff);

        let strip = |word_diff: bool| {
            let opts = crate::options::ViewOptions {
                word_diff,
                ..Default::default()
            };
            let mut buffer = Vec::new();
            view.render_with_options(&mut buffer, 100, 24, &opts)
                .expect("render succeeds");
            let text = String::from_utf8_lossy(&buffer).into_owned();
            // Drop every escape sequence, keeping only printable payload.
            let mut out = String::new();
            let mut chars = text.chars();
            while let Some(c) = chars.next() {
                if c == '\x1b' {
                    for t in chars.by_ref() {
                        if t.is_ascii_alphabetic() {
                            break;
                        }
                    }
                } else {
                    out.push(c);
                }
            }
            out
        };

        assert_eq!(strip(true), strip(false));
    }

