    // --- Word-level (intra-line) diff emphasis ---

    fn hunk_line(kind: DiffLineKind, content: &str) -> HunkLine {
        HunkLine {
            kind,
            content: content.to_string(),
            no_newline_at_eof: false,
        }
    }

    /// Builds a one-file, one-hunk diff from the given hunk lines.
    fn diff_with_lines(hunk_lines: Vec<HunkLine>) -> CommitDiff {
        let sha1 = ObjectId::empty_tree(gix::hash::Kind::Sha1);
        CommitDiff {
            commit_id: sha1,
            parent_ids: vec![],
            author_name: Arc::from("Alice"),
            author_email: Arc::from("alice@example.com"),
            author_date: "Mon Sep 1 12:00:00 2026 +0000".to_string(),
            committer_name: Arc::from("Alice"),
            committer_email: Arc::from("alice@example.com"),
            committer_date: "Mon Sep 1 12:00:00 2026 +0000".to_string(),
            title: Arc::from("Change"),
            body: None,
            files: vec![FileDiff {
                path: "src/lib.rs".to_string(),
                status: FileChangeStatus::Modified,
                old_id: Some(sha1),
                new_id: Some(sha1),
                old_mode: Some(0o100_644),
                new_mode: Some(0o100_644),
                is_binary: false,
                additions: 1,
                deletions: 1,
                hunks: vec![DiffHunk {
                    old_start: 1,
                    old_len: 1,
                    new_start: 1,
                    new_len: 1,
                    func_context: None,
                    lines: hunk_lines,
                }],
            }],
            stats: DiffSummaryStats::default(),
        }
    }

    /// Extracts the emphasised substrings of the first line of the given kind
    /// whose text contains `needle`.
    ///
    /// Matching is by `DiffLineType` rather than by leading character because
    /// the `---` / `+++` file headers also begin with `-` and `+`.
    fn emphasised_text(view: &DiffView, kind: DiffLineType, needle: &str) -> Vec<String> {
        let row = view
            .document
            .rows
            .iter()
            .find(|r| r.row_type == kind && r.search_text().contains(needle))
            .expect("line present");
        let cell = row.left.as_ref().unwrap();
        let chars: Vec<char> = cell.text.chars().collect();
        cell.emphasis
            .iter()
            .map(|&(s, e)| chars[s as usize..e as usize].iter().collect())
            .collect()
    }

    #[test]
    fn test_word_diff_marks_only_changed_token_in_pair() {
        let diff = diff_with_lines(vec![
            hunk_line(DiffLineKind::Context, "fn main() {"),
            hunk_line(DiffLineKind::Remove, "    let total = compute_total(a, b);"),
            hunk_line(DiffLineKind::Add, "    let total = compute_sum(a, b);"),
        ]);
        let view = DiffView::new(diff);

        assert_eq!(
            emphasised_text(&view, DiffLineType::DiffDel, "let total"),
            vec!["compute_total"]
        );
        assert_eq!(
            emphasised_text(&view, DiffLineType::DiffAdd, "let total"),
            vec!["compute_sum"]
        );
    }

    #[test]
    fn test_word_diff_offsets_account_for_diff_prefix() {
        // Word diffing is token-based and suppresses pairs where *both* sides
        // are almost entirely rewritten, so the fixture has to keep most of the
        // line intact for any emphasis to survive.
        let diff = diff_with_lines(vec![
            hunk_line(DiffLineKind::Remove, "let x = 1;"),
            hunk_line(DiffLineKind::Add, "let x = 2;"),
        ]);
        let view = DiffView::new(diff);

        let del_row = view
            .document
            .rows
            .iter()
            .find(|r| r.row_type == DiffLineType::DiffDel)
            .expect("del line");
        let del = del_row.left.as_ref().unwrap();
        // In cell.text ("let x = 1;"), token '1' is at 8..9.
        // In search_text ("-let x = 1;"), token '1' is at 9..10.
        assert_eq!(del.emphasis, vec![(8, 9)]);
        assert_eq!(&del.text[8..9], "1");
        assert_eq!(&del_row.search_text()[9..10], "1");
    }

