    /// Returns the text to copy (`y`) at the current cursor row.
    ///
    /// On a `FileHeader` (including single-line banners) or when the File Details popover is open,
    /// always returns the canonical `diff --git` multi-line header block.
    /// On a `HunkHeader` (including human-readable separators), always returns the canonical
    /// `@@ -old,len +new,len @@ func` header.
    #[must_use]
    pub fn yank_text_at_cursor(&self) -> Option<String> {
        if self.show_file_details {
            let f_idx = self.current_file_index().unwrap_or(0);
            return self
                .diff
                .files
                .get(f_idx)
                .map(crate::diff::layout::format_real_file_header);
        }
        let row = self.document.rows.get(self.nav.cursor)?;
        match row.row_type {
            DiffLineType::FileHeader | DiffLineType::Delimiter | DiffLineType::ModeChange => {
                let f_idx = self.current_file_index()?;
                self.diff
                    .files
                    .get(f_idx)
                    .map(crate::diff::layout::format_real_file_header)
            }
            DiffLineType::HunkHeader => {
                let loc = self
                    .document
                    .line_to_hunk
                    .get(self.nav.cursor)
                    .copied()
                    .flatten()
                    .or(row.anchor)?;
                self.diff
                    .files
                    .get(loc.file_idx)
                    .and_then(|f| f.hunks.get(loc.hunk_idx))
                    .map(crate::diff::layout::format_real_hunk_header)
            }
            _ => row
                .left
                .as_ref()
                .or(row.right.as_ref())
                .map(|c| c.text.to_string()),
        }
    }

    /// Renders the complete diff view to the terminal using default options.
